// Synthesizes the 17 pet sound effects: a happy and a sad vocalisation for every species and
// hatched stage (baby, juvenile, adult, legend), plus the shared sparkle chime played on dances
// and hatches. Output files are committed, so run this whenever tuning the vocal models and
// listen to the result:
//
//   node scripts/generate-pet-sounds.mjs
//
// Writes identical 22050 Hz, 16-bit mono PCM WAV files to apps/mobile/assets/sounds/pet/ and
// apps/web/public/pet/sounds/, removes stale WAVs in those directories, and regenerates the
// static mobile asset map in apps/mobile/src/features/pet/pet-sound-assets.ts.
import { execFileSync } from "node:child_process";
import { mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

import { hippoAndPigClips } from "./pet-sounds/clips-hippo-pig.mjs";
import { SAMPLE_RATE, encodeWav, finalizeClip, measureLoudness } from "./pet-sounds/dsp.mjs";

export { SAMPLE_RATE, encodeWav, measureLoudness };

const OUTPUT_DIRS = ["apps/mobile/assets/sounds/pet", "apps/web/public/pet/sounds"];
const MOBILE_ASSET_MAP = "apps/mobile/src/features/pet/pet-sound-assets.ts";

/** Every clip by file name (without `.wav`), loudness-matched and peak-limited in [-1, 1]. */
export function petClips() {
  const raw = hippoAndPigClips();

  return Object.fromEntries(
    Object.entries(raw)
      .sort(([a], [b]) => a.localeCompare(b))
      .map(([name, samples]) => [name, finalizeClip(samples)]),
  );
}

const camel = (name) => name.replace(/-(\w)/g, (_match, letter) => letter.toUpperCase());

/** Builds the static Metro asset map consumed by apps/mobile/src/features/pet/pet-sounds.ts. */
export function buildMobileAssetMap(clipNames) {
  const voiceNames = clipNames.filter((name) => name !== "sparkle").sort();
  const imports = [
    ...voiceNames.map(
      (name) => `import ${camel(name)} from "../../../assets/sounds/pet/${name}.wav";`,
    ),
    `import sparkle from "../../../assets/sounds/pet/sparkle.wav";`,
  ];
  const entries = voiceNames.map((name) => `  "${name}": ${camel(name)},`);
  return [
    "// Generated by scripts/generate-pet-sounds.mjs; do not edit by hand.",
    'import type { PetVoiceClip } from "@zoption/shared";',
    "",
    ...imports,
    "",
    "/** Every species and stage voice clip, statically imported so Metro bundles them. */",
    "export const petVoiceAssets: Record<PetVoiceClip, number> = {",
    ...entries,
    "};",
    "",
    "/** Shared celesta sparkle played on combo dances and egg hatches. */",
    "export const sparkleAsset: number = sparkle;",
    "",
  ].join("\n");
}

function main() {
  const root = join(dirname(fileURLToPath(import.meta.url)), "..");
  const clips = petClips();
  const expectedFiles = new Set(Object.keys(clips).map((name) => `${name}.wav`));

  for (const dir of OUTPUT_DIRS) {
    const absDir = join(root, dir);
    mkdirSync(absDir, { recursive: true });
    for (const file of readdirSync(absDir)) {
      if (file.endsWith(".wav") && !expectedFiles.has(file)) {
        rmSync(join(absDir, file));
      }
    }
    for (const [name, samples] of Object.entries(clips)) {
      writeFileSync(join(absDir, `${name}.wav`), encodeWav(samples));
    }
  }

  const mapPath = join(root, MOBILE_ASSET_MAP);
  writeFileSync(mapPath, buildMobileAssetMap(Object.keys(clips)));
  execFileSync("pnpm", ["exec", "prettier", "--write", mapPath], {
    cwd: root,
    stdio: "inherit",
  });
  console.log(
    `Wrote ${Object.keys(clips).length} clips to ${OUTPUT_DIRS.join(" and ")} and updated ${MOBILE_ASSET_MAP}.`,
  );
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) main();
