function pigOink({
  duration,
  gruntHz,
  oinkHz,
  oinkAmount,
  formantShift = 1,
  drive = 1.25,
  snortGain = 0.42,
  seed,
}) {
  const snort = nasalSnuffle({
    duration: Math.min(0.042, duration * 0.28),
    direction: "inhale",
    size: formantShift > 1.2 ? "small" : "medium",
    flutterRate: 48,
    flutterDepth: 0.5,
    cutoffHz: 2800,
    seed: seed + 50,
  });
  const peakHz = gruntHz + (oinkHz - gruntHz) * oinkAmount;
  const f = (hz) => hz * formantShift;
  const call = animalCall({
    duration,
    pitch: [
      0,
      gruntHz * 0.94,
      0.32,
      gruntHz * 1.12,
      0.74,
      peakHz,
      0.9,
      peakHz * 0.86,
      1,
      gruntHz * 1.04,
    ],
    spectralTilt: "0:0.6 0.38:0.56 0.78:0.7 1:0.84",
    f0Body: "0:0.16 0.38:0.14 0.78:0.08 1:0.12",
    drive,
    jitter: 0.04,
    shimmer: 0.14,
    subharmonics: formantShift > 1.2 ? 0.15 : "0:0.42 0.38:0.34 0.75:0.1 1:0.15",
    rattle: {
      rate: formantShift > 1.2 ? [54, 62] : [36, 44],
      fmSemitones: "0:0.4 0.42:0.3 0.8:0.1 1:0.14",
      amDepth: "0:0.45 0.42:0.35 0.78:0.12 1:0.18",
    },
    aspiration: "0:0.22 0.45:0.14 0.82:0.1 1:0.2",
    aspirationFormants: [
      [f(400), 180, 1.0],
      [f(1180), 360, 0.75],
    ],
    formants: [
      [[0, f(350), 0.38, f(430), 0.78, f(320), 1, f(280)], 85, 0.88],
      [[0, f(540), 0.36, f(680), 0.76, f(460), 1, f(370)], 110, 1.0],
      [[0, f(840), 0.34, f(980), 0.78, f(1020 + 920 * oinkAmount), 1, f(1380)], 140, 1.0],
      [[0, f(1850), 0.36, f(2080), 0.78, f(2150 + 580 * oinkAmount), 1, f(2260)], 210, 0.62],
    ],
    cutoffHz: 4300,
    attack: 0.006,
    release: 0.022,
    contour: "0:0.68 0.22:0.94 0.42:0.84 0.76:1.0 1:0.08",
    seed,
  });
  return mix([
    [0.0, snort, snortGain],
    [0.01, call, 1.0],
  ]);
}

