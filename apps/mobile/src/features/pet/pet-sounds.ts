import {
  petSoundCue,
  petVoiceClip,
  type PetReaction,
  type PetSpecies,
  type PetStage,
} from "@zoption/shared";
import * as Haptics from "expo-haptics";

import hamsterHappy from "../../../assets/sounds/pet/hamster-happy.wav";
import hamsterSad from "../../../assets/sounds/pet/hamster-sad.wav";
import hedgehogHappy from "../../../assets/sounds/pet/hedgehog-happy.wav";
import hedgehogSad from "../../../assets/sounds/pet/hedgehog-sad.wav";
import hippoHappy from "../../../assets/sounds/pet/hippo-happy.wav";
import hippoSad from "../../../assets/sounds/pet/hippo-sad.wav";
import pandaHappy from "../../../assets/sounds/pet/panda-happy.wav";
import pandaSad from "../../../assets/sounds/pet/panda-sad.wav";
import penguinHappy from "../../../assets/sounds/pet/penguin-happy.wav";
import penguinSad from "../../../assets/sounds/pet/penguin-sad.wav";
import pigHappy from "../../../assets/sounds/pet/pig-happy.wav";
import pigSad from "../../../assets/sounds/pet/pig-sad.wav";
import sparkle from "../../../assets/sounds/pet/sparkle.wav";
import { playClip, warmUpClips } from "@/features/sounds/sound-effects";

// Static imports, because Metro only bundles assets it can see. Generated by
// scripts/generate-pet-sounds.mjs.
const VOICES: Record<ReturnType<typeof petVoiceClip>, number> = {
  "hamster-happy": hamsterHappy,
  "hamster-sad": hamsterSad,
  "hedgehog-happy": hedgehogHappy,
  "hedgehog-sad": hedgehogSad,
  "hippo-happy": hippoHappy,
  "hippo-sad": hippoSad,
  "panda-happy": pandaHappy,
  "panda-sad": pandaSad,
  "penguin-happy": penguinHappy,
  "penguin-sad": penguinSad,
  "pig-happy": pigHappy,
  "pig-sad": pigSad,
};

/** Loads one pet's voices and the sparkle ahead of the first tap. */
export function warmUpPetVoices(species: PetSpecies): void {
  warmUpClips([
    VOICES[petVoiceClip(species, "happy")],
    VOICES[petVoiceClip(species, "sad")],
    sparkle,
  ]);
}

/**
 * Answers a tap on the pet with its own voice (pitched by stage, plus the sparkle on a dance) and
 * a buzz: light for a tap, a success pattern for a dance. The voice follows the Sound effects
 * switch; the buzz follows the system's haptics setting. Both are fire and forget.
 */
export function playPetReaction(
  species: PetSpecies,
  stage: Exclude<PetStage, "egg">,
  reaction: PetReaction,
): void {
  const cue = petSoundCue(stage, reaction);
  playClip(VOICES[petVoiceClip(species, cue.voice)], { rate: cue.rate, volume: cue.volume });
  if (cue.sparkle) playClip(sparkle);
  const buzz =
    reaction === "combo"
      ? Haptics.notificationAsync(Haptics.NotificationFeedbackType.Success)
      : Haptics.impactAsync(Haptics.ImpactFeedbackStyle.Light);
  buzz.catch(() => {
    // Haptics are decoration; a device without them stays quiet.
  });
}
